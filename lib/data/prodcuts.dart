String catalogImage(String key, {int width = 600, int height = 600}) {
  final source = _images[key];
  if (source == null) {
    throw ArgumentError.value(key, 'key', 'No catalog image is configured');
  }
  if (source.startsWith('un:')) {
    return 'https://images.unsplash.com/${source.substring(3)}'
        '?auto=format&fit=crop&w=$width&h=$height&q=85';
  }
  if (source.startsWith('px:')) {
    final id = source.substring(3);
    return 'https://images.pexels.com/photos/$id/pexels-photo-$id.jpeg'
        '?auto=compress&cs=tinysrgb&fit=crop&w=$width&h=$height';
  }
  if (source.startsWith('dj:')) {
    // Square 1000 px renders on a transparent background.
    return 'https://cdn.dummyjson.com/product-images/${source.substring(3)}';
  }
  return source;
}

String _img(String seed, [int w = 600, int h = 600]) =>
    catalogImage(seed, width: w, height: h);

/// First key is the cover; option `imageIndex` values point into this list.
List<String> _gallery(String seed, [List<String> more = const []]) => [
  _img(seed),
  for (final key in more) _img(key),
];

